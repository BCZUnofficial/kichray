# Windows port of embed_shaders.py for machines without Python: identical
# output (json.dumps per source line, ASCII HLSL), written with CRLF.
#   powershell -ExecutionPolicy Bypass -File tests\r4_deferred\embed_shaders.ps1 [-Check]
param([switch]$Check)
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$source = [IO.File]::ReadAllText((Join-Path $root 'resources\shaders\r4\bridge_deferred.hlsl'))
$lines = $source -split "`r`n|`n|`r"
if ($lines.Count -gt 0 -and $lines[-1] -eq '') { $lines = $lines[0..($lines.Count - 2)] }
function JsonString([string]$s) {
    $b = New-Object System.Text.StringBuilder
    [void]$b.Append('"')
    foreach ($c in $s.ToCharArray()) {
        switch ($c) {
            '"' { [void]$b.Append('\"') }
            '\' { [void]$b.Append('\\') }
            "`n" { [void]$b.Append('\n') }
            "`r" { [void]$b.Append('\r') }
            "`t" { [void]$b.Append('\t') }
            default {
                if ([int]$c -lt 32 -or [int]$c -gt 126) { [void]$b.Append(('\u{0:x4}' -f [int]$c)) }
                else { [void]$b.Append($c) }
            }
        }
    }
    [void]$b.Append('"')
    $b.ToString()
}
$body = ($lines | ForEach-Object { JsonString ($_ + "`n") }) -join "`n"
$result = "// Generated by tests/r4_deferred/embed_shaders.py.`n#ifndef KICH_R4_DEFERRED_SHADERS_H`n#define KICH_R4_DEFERRED_SHADERS_H`ninline const char* KichR4DeferredShaderSource(){return`n" + $body + ";}`n#endif`n"
$result = $result -replace "`n", "`r`n"
$target = Join-Path $root 'xr_3da\KichR4DeferredShaders.h'
if ($Check) {
    if (-not (Test-Path $target) -or [IO.File]::ReadAllText($target) -ne $result) { Write-Output 'Embedded HLSL is stale; run embed_shaders.ps1'; exit 1 }
    Write-Output 'PASS: embedded shader source matches canonical HLSL'
} else { [IO.File]::WriteAllText($target, $result, (New-Object System.Text.ASCIIEncoding)) }
