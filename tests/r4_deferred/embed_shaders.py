#!/usr/bin/env python3
"""Keep the in-EXE source identical to the canonical HLSL; no gamedata install."""
from pathlib import Path
import json
import sys
root = Path(__file__).resolve().parents[2]
source = (root / "resources/shaders/r4/bridge_deferred.hlsl").read_text()
result = ('// Generated by tests/r4_deferred/embed_shaders.py.\n'
          '#ifndef KICH_R4_DEFERRED_SHADERS_H\n#define KICH_R4_DEFERRED_SHADERS_H\n'
          'inline const char* KichR4DeferredShaderSource(){return\n' +
          '\n'.join(json.dumps(line + '\n') for line in source.splitlines()) + ';}\n#endif\n')
target = root / 'xr_3da/KichR4DeferredShaders.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != result:
        raise SystemExit('Embedded HLSL is stale; run embed_shaders.py')
    print('PASS: embedded shader source matches canonical HLSL')
else:
    target.write_text(result)
